"""UI translations following Blender's language setting.

Mechanism: ``bpy.app.translations`` (proposal §5.8). All code writes
English msgids; Blender looks up the translation for the current
language. No language switch of our own; the language follows Blender's
preference (``preferences.view.language``).

Two facts verified headless on 4.5.16 and 5.1.2 (2026-11-17 probes,
NOT from memory):

1. The Simplified Chinese locale key is ``zh_HANS``, not ``zh_CN``
   (``zh_CN`` is absent from ``bpy.app.translations.locales`` and from
   the language enum). ``zh_CN`` is registered as well as a harmless
   alias.
2. Only the ``"*"`` context is consulted by ``pgettext_iface`` /
   ``pgettext`` for add-on dictionaries; entries keyed with
   ``("Interface", ...)`` or ``("Operator", ...)`` are ignored.
   Every entry here is therefore keyed ``("*", msgid)``.

Known limitation (mechanism, not a bug in this file): when a msgid
collides with a string Blender itself translates (e.g. "Flip"),
Blender's built-in translation wins over the add-on dictionary, so the
menu may show Blender's Chinese (翻转) instead of SketchUp's (镜像).
The T2 diagnostics print the full collision list under zh_HANS.

Real-machine correction (2026-11-17, Sen's Windows 5.1.2): text passed
to ``layout.operator(text=...)`` is shown VERBATIM — Blender does not
translate it — while ``layout.menu(text=...)`` titles are translated.
So relying on the registered dictionary alone left every menu leaf in
English under a Chinese UI. All draw code MUST resolve its strings
explicitly with :func:`translate` before passing them to layout calls.
The registered dictionary is kept only for class-level labels
(``bl_label``, enum items) that Blender translates itself.
"""

