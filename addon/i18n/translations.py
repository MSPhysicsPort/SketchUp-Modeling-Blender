_ZH_DICT = {("*", msgid): text for msgid, text in _ZH}
_ZH_MAP = dict(_ZH)

TRANSLATIONS = {
    "zh_HANS": dict(_ZH_DICT),
    "zh_CN": dict(_ZH_DICT),
}


def translate(msgid):
    """Resolve a UI string explicitly for the current Blender language.

    Returns the Simplified Chinese text when the current locale is
    Chinese, otherwise the English msgid unchanged. Missing entries
    fall back to the msgid (never blank, never an error).

    Every string passed to a ``layout.*`` call in draw code must go
    through this function: operator text is shown verbatim by Blender.
    """
    import bpy

    try:
        locale = bpy.app.translations.locale
    except Exception:
        return msgid
    if isinstance(locale, str) and locale.startswith("zh"):
        return _ZH_MAP.get(msgid, msgid)
    return msgid


def register(module_name):
    """Register the translation dictionary (call from register())."""
    import bpy

    bpy.app.translations.register(module_name, TRANSLATIONS)


def unregister(module_name):
    """Remove the translation dictionary (call from unregister())."""
    import bpy

    bpy.app.translations.unregister(module_name)
